# Regenerates the banned-word patterns in firestore.rules (run after editing the lists below,
# keep them in step with src/moderation.ts), then deploy the rules.
import re
import os
p = os.path.join(os.path.dirname(__file__), '..', 'firestore.rules')
s = open(p, encoding='utf8').read()
# Build the server patterns with look-alike character classes (mirrors the client's mapping).
L = {'a': '[a4@]', 'e': '[e3]', 'i': '[i1!|]', 'o': '[o0]', 's': '[s5$]', 't': '[t7+]', 'g': '[g9]', 'b': '[b8]'}
def fuzzy(word):
    out = ''
    for ch in word:
        out += (L.get(ch, re.escape(ch)) + '+')  # "+" also catches stretched letters (fuuuck)
    return out
anywhere = ['nigger', 'nigga', 'faggot', 'kike', 'wetback', 'tranny', 'raghead', 'towelhead', 'beaner', 'fuck', 'bullshit', 'shithead', 'shitty', 'whore', 'slut', 'bitch', 'hitler', 'killyourself', 'paedo', 'pedophil', 'molest']
whole = ['nazi', 'nazis', 'shit', 'retard', 'retarded', 'chink', 'spic', 'coon', 'gook', 'paki', 'dyke', 'cunt', 'rape', 'rapist', 'pedo', 'kys', 'ass', 'arse', 'fag', 'cum', 'dick', 'cock', 'twat', 'wank', 'jizz', 'porn', 'sex', 'anal', 'tits']
a = '|'.join(fuzzy(w) for w in anywhere) + '|k\\W*k\\W*k'
w = '|'.join(fuzzy(x) for x in whole)
esc = lambda x: x.replace('\\', '\\\\').replace("'", "\\'")
new = ("      return !s.matches('(?s).*(" + esc(a) + ").*')\n"
       "        && !s.matches('(?s)(.*[^a-z0-9])?(" + esc(w) + ")([^a-z0-9].*)?');")
start = s.index("      return !s.matches('(?s).*(")
end = s.index(");\n", s.index("&& !s.matches('(?s)(.*[^a-z", start)) + 3
s = s[:start] + new + '\n' + s[end:]
s = s.replace("    // Banned words: slurs, hate terms and severe profanity. Mirrors src/moderation.ts (which\n    // also catches look-alike spellings before anything is sent).",
              "    // Banned words: slurs, hate terms and severe profanity, including look-alike spellings\n    // (n1gg3r, fuuuck). Same list as src/moderation.ts; generated by scripts/rules-blocklist.py.")
open(p, 'w', encoding='utf8').write(s)
print('updated firestore.rules blocklist')
